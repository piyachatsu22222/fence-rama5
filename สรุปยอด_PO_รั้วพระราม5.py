def รวมยอดตาม_PO(รายการทั้งหมด: list[รายการเงิน]) -> dict[str, สรุปราย_PO]:
    """ทำหน้าที่เดียวกับ PivotTable: จับกลุ่มตาม PO แล้วบวกยอด"""
    ตาราง: dict[str, สรุปราย_PO] = {}
    for รายการ in รายการทั้งหมด:
        # ใช้ตัวพิมพ์ใหญ่เป็นกุญแจ เพื่อให้ po-6606-001 กับ PO-6606-001 รวมเป็นใบเดียวกัน
        กุญแจ = รายการ.po.upper()
        if กุญแจ not in ตาราง:
            ตาราง[กุญแจ] = สรุปราย_PO(po=กุญแจ)
        รวม = ตาราง[กุญแจ]
        รวม.ยอดรับ += รายการ.ยอดรับ
        รวม.ยอดจ่าย += รายการ.ยอดจ่าย
        รวม.จำนวนแถว += 1
        รวม.ไฟล์ที่พบ.add(Path(รายการ.ไฟล์).name)
    return ตาราง


