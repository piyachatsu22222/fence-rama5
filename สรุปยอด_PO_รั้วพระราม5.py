def หา_es_exe(ระบุเอง: str | None = None) -> str | None:
    """หาตัว es.exe (Everything Command-line) — คืน path ถ้าเจอ ไม่เจอคืน None"""
    if ระบุเอง:
        return ระบุเอง if Path(ระบุเอง).exists() else None
    เจอใน_path = shutil.which("es") or shutil.which("es.exe")
    if เจอใน_path:
        return เจอใน_path
    ที่มักเก็บไว้ = [
        r"C:\Program Files\Everything\es.exe",
        r"C:\Program Files (x86)\Everything\es.exe",
        r"C:\Tools\es.exe",
        str(Path.home() / "Documents" / "es.exe"),
        str(Path.home() / "Documents" / "Claude_Setup" / "es.exe"),
        str(Path.home() / "Downloads" / "es.exe"),
    ]
    for ที่ in ที่มักเก็บไว้:
        if Path(ที่).exists():
            return ที่
    return None


def อ่านไฟล์ผลลัพธ์(ที่อยู่: str) -> list[str]:
    """อ่านไฟล์ที่ es.exe export ออกมา — ลองหลาย encoding เพราะภาษาไทยชอบเพี้ยน"""
    for รหัส in ("utf-8-sig", "utf-8", "utf-16", "cp874", "mbcs"):
        try:
            with open(ที่อยู่, "r", encoding=รหัส) as ไฟล์:
                บรรทัด = [b.strip() for b in ไฟล์ if b.strip()]
            if บรรทัด:
                return บรรทัด
        except (UnicodeDecodeError, LookupError, OSError):
            continue
    return []


def ค้นด้วย_Everything(es: str, คำค้น: str, ตั้งแต่: str, ถึง: str) -> list[Path]:
    """
    ยิงคำค้นชุดเดียวกับที่พิมพ์ในหน้าต่าง Everything:
        รั้ว พระราม 5 ext:xlsx dm:2023-06-01..2024-02-29
    """
    เงื่อนไข = คำค้น.split() + ["ext:xlsx;xlsm", f"dm:{ตั้งแต่}..{ถึง}"]
    ไฟล์ชั่วคราว = Path(tempfile.gettempdir()) / f"es_result_{os.getpid()}.txt"
    คำสั่ง = [es, "-full-path-and-name", "-export-txt", str(ไฟล์ชั่วคราว)] + เงื่อนไข
    log.info("เรียก Everything: %s", " ".join(คำสั่ง[1:]))
    try:
        ผล = subprocess.run(คำสั่ง, capture_output=True, timeout=180)
        if ผล.returncode != 0:
            log.warning("es.exe คืนค่า %s — จะสแกนโฟลเดอร์เองแทน", ผล.returncode)
            return []
        รายชื่อ = อ่านไฟล์ผลลัพธ์(str(ไฟล์ชั่วคราว))
    except (OSError, subprocess.SubprocessError) as ข้อผิดพลาด:
        log.warning("เรียก es.exe ไม่สำเร็จ (%s) — จะสแกนโฟลเดอร์เองแทน", ข้อผิดพลาด)
        return []
    finally:
        try:
            ไฟล์ชั่วคราว.unlink(missing_ok=True)
        except OSError:
            pass
    return [Path(บ) for บ in รายชื่อ
            if บ.lower().endswith(นามสกุลที่อ่านได้) and not Path(บ).name.startswith("~$")]


def สแกนโฟลเดอร์เอง(รากทั้งหมด: list[str], คำค้น: str, ตั้งแต่: datetime, ถึง: datetime,
                    ดูทั้งพาธ: bool = False) -> list[Path]:
    """
    สแกนหาไฟล์เองแบบไม่ง้อ Everything — ใช้กติกาเดียวกับ Everything คือ
    เว้นวรรค = ต้องมีครบทุกคำ (AND) และกรองตามวันที่แก้ไขไฟล์
    """
    คำทั้งหมด = [ปรับข้อความ(ค) for ค in คำค้น.split() if ค.strip()]
    ที่เจอ: list[Path] = []
    for ราก in รากทั้งหมด:
        โฟลเดอร์ราก = Path(ราก).expanduser()
        if not โฟลเดอร์ราก.is_dir():
            log.warning("ข้ามโฟลเดอร์ที่ไม่มีอยู่จริง: %s", ราก)
            continue
        log.info("สแกนโฟลเดอร์: %s", โฟลเดอร์ราก)
        for ที่อยู่, โฟลเดอร์ย่อย, รายชื่อไฟล์ in os.walk(โฟลเดอร์ราก, onerror=lambda e: log.debug("ข้าม: %s", e)):
            # ไม่ต้องเข้าไปในโฟลเดอร์ระบบ/ซ่อน จะได้ไม่ช้า
            โฟลเดอร์ย่อย[:] = [ด for ด in โฟลเดอร์ย่อย if not ด.startswith((".", "$", "~"))]
            for ชื่อไฟล์ in รายชื่อไฟล์:
                if not ชื่อไฟล์.lower().endswith(นามสกุลที่อ่านได้) or ชื่อไฟล์.startswith("~$"):
                    continue
                เต็ม = Path(ที่อยู่) / ชื่อไฟล์
                เป้าเทียบ = ปรับข้อความ(str(เต็ม) if ดูทั้งพาธ else ชื่อไฟล์)
                if not all(คำ in เป้าเทียบ for คำ in คำทั้งหมด):
                    continue
                try:
                    แก้ไขเมื่อ = datetime.fromtimestamp(เต็ม.stat().st_mtime)
                except OSError:
                    continue
                if ตั้งแต่ <= แก้ไขเมื่อ <= ถึง:
                    ที่เจอ.append(เต็ม)
    return ที่เจอ


