def เขียนไฟล์สรุป(ที่อยู่ออก: Path, ตารางสรุป: dict[str, สรุปราย_PO],
                  รายการทั้งหมด: list[รายการเงิน], สถานะไฟล์: list[dict], ข้อมูลการรัน: list[tuple]) -> None:
    """สร้าง Excel สรุป 4 ชีต: สรุปตาม PO / รายละเอียด / ไฟล์ที่อ่าน / ข้อมูลการรัน"""
    from openpyxl import Workbook
    from openpyxl.styles import Alignment, Border, Font, PatternFill, Side
    from openpyxl.utils import get_column_letter

    รูปแบบเงิน = '#,##0.00;[Red]-#,##0.00'
    สีหัว = PatternFill("solid", fgColor="1E1E2E")
    ฟอนต์หัว = Font(bold=True, color="FFFFFF", name="Tahoma", size=11)
    ฟอนต์รวม = Font(bold=True, name="Tahoma", size=11)
    สีรวม = PatternFill("solid", fgColor="DDE7FA")
    เส้นบน = Border(top=Side(style="thin", color="89B4FA"))

    def วางหัว(ชีต, หัวข้อ: list[str], ความกว้าง: list[int]):
        ชีต.append(หัวข้อ)
        for ลำดับ, _ in enumerate(หัวข้อ, start=1):
            เซลล์ = ชีต.cell(row=1, column=ลำดับ)
            เซลล์.fill, เซลล์.font = สีหัว, ฟอนต์หัว
            เซลล์.alignment = Alignment(horizontal="center", vertical="center", wrap_text=True)
            ชีต.column_dimensions[get_column_letter(ลำดับ)].width = ความกว้าง[ลำดับ - 1]
        ชีต.freeze_panes = "A2"
        ชีต.row_dimensions[1].height = 22

    สมุดงาน = Workbook()

    # ---------- ชีต 1: สรุปตาม PO (ตัวหลักที่ใช้จริง) ----------
    ชีต1 = สมุดงาน.active
    ชีต1.title = "สรุปตาม PO"
    วางหัว(ชีต1, ["เลขที่ PO", "ยอดรับ", "ยอดจ่าย", "ยอดสุทธิ", "จำนวนรายการ", "จำนวนไฟล์"],
           [26, 16, 16, 16, 12, 10])
    เรียงแล้ว = sorted(ตารางสรุป.values(), key=lambda ร: ร.po)
    for รวม in เรียงแล้ว:
        ชีต1.append([รวม.po, รวม.ยอดรับ, รวม.ยอดจ่าย, รวม.ยอดสุทธิ, รวม.จำนวนแถว, len(รวม.ไฟล์ที่พบ)])
    for แถว in ชีต1.iter_rows(min_row=2, min_col=2, max_col=4):
        for เซลล์ in แถว:
            เซลล์.number_format = รูปแบบเงิน
    if เรียงแล้ว:
        แถวรวม = ชีต1.max_row + 1
        ชีต1.cell(row=แถวรวม, column=1, value="รวมทั้งสิ้น")
        for คอลัมน์ in (2, 3, 4):
            อักษร = get_column_letter(คอลัมน์)
            เซลล์ = ชีต1.cell(row=แถวรวม, column=คอลัมน์,
                              value=f"=SUM({อักษร}2:{อักษร}{แถวรวม - 1})")
            เซลล์.number_format = รูปแบบเงิน
        for คอลัมน์ in range(1, 7):
            เซลล์ = ชีต1.cell(row=แถวรวม, column=คอลัมน์)
            เซลล์.font, เซลล์.fill, เซลล์.border = ฟอนต์รวม, สีรวม, เส้นบน
        ชีต1.auto_filter.ref = f"A1:F{แถวรวม - 1}"

    # ---------- ชีต 2: รายละเอียดทุกแถวที่ดึงมา (ไว้ไล่ตรวจย้อนกลับ) ----------
    ชีต2 = สมุดงาน.create_sheet("รายละเอียด")
    วางหัว(ชีต2, ["เลขที่ PO", "ยอดรับ", "ยอดจ่าย", "ชื่อไฟล์", "ชีต", "แถวที่", "พาธเต็ม"],
           [24, 14, 14, 40, 18, 8, 70])
    for รายการ in รายการทั้งหมด:
        ชีต2.append([รายการ.po, รายการ.ยอดรับ, รายการ.ยอดจ่าย,
                     Path(รายการ.ไฟล์).name, รายการ.ชีต, รายการ.เลขแถว, รายการ.ไฟล์])
    for แถว in ชีต2.iter_rows(min_row=2, min_col=2, max_col=3):
        for เซลล์ in แถว:
            เซลล์.number_format = รูปแบบเงิน
    if ชีต2.max_row > 1:
        ชีต2.auto_filter.ref = f"A1:G{ชีต2.max_row}"

    # ---------- ชีต 3: ไฟล์ที่อ่าน + สถานะ (ไฟล์ไหนอ่านไม่ได้จะเห็นตรงนี้) ----------
    ชีต3 = สมุดงาน.create_sheet("ไฟล์ที่อ่าน")
    วางหัว(ชีต3, ["ชื่อไฟล์", "วันที่แก้ไข", "ขนาด (KB)", "สถานะ", "พาธเต็ม"], [42, 18, 12, 46, 70])
    for แถว in สถานะไฟล์:
        ชีต3.append([แถว["ชื่อ"], แถว["แก้ไข"], แถว["ขนาด"], แถว["สถานะ"], แถว["พาธ"]])
    if ชีต3.max_row > 1:
        ชีต3.auto_filter.ref = f"A1:E{ชีต3.max_row}"

    # ---------- ชีต 4: บันทึกว่ารันด้วยเงื่อนไขอะไร (กันงงตอนย้อนดูทีหลัง) ----------
    ชีต4 = สมุดงาน.create_sheet("ข้อมูลการรัน")
    วางหัว(ชีต4, ["หัวข้อ", "ค่า"], [28, 80])
    for หัวข้อ, ค่า in ข้อมูลการรัน:
        ชีต4.append([หัวข้อ, str(ค่า)])

    ที่อยู่ออก.parent.mkdir(parents=True, exist_ok=True)
    สมุดงาน.save(ที่อยู่ออก)


