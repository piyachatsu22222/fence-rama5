def พิมพ์ตารางสรุป(ตารางสรุป: dict[str, สรุปราย_PO], จำกัด: int = 0) -> None:
    if not ตารางสรุป:
        print("\n  ไม่พบข้อมูล PO ในไฟล์ที่อ่านได้\n")
        return

    เรียงแล้ว = sorted(ตารางสรุป.values(), key=lambda ร: ร.po)
    แสดง = เรียงแล้ว[:จำกัด] if จำกัด else เรียงแล้ว

    หัวข้อ = ["เลขที่ PO", "ยอดรับ", "ยอดจ่าย", "ยอดสุทธิ"]
    แถวข้อความ = [[ร.po, จัดรูปแบบเงิน(ร.ยอดรับ), จัดรูปแบบเงิน(ร.ยอดจ่าย), จัดรูปแบบเงิน(ร.ยอดสุทธิ)]
                  for ร in แสดง]
    รวมรับ = sum(ร.ยอดรับ for ร in เรียงแล้ว)
    รวมจ่าย = sum(ร.ยอดจ่าย for ร in เรียงแล้ว)
    แถวรวม = ["รวมทั้งสิ้น", จัดรูปแบบเงิน(รวมรับ), จัดรูปแบบเงิน(รวมจ่าย), จัดรูปแบบเงิน(รวมรับ - รวมจ่าย)]

    ทุกแถว = [หัวข้อ, แถวรวม] + แถวข้อความ
    กว้าง = [max(ความกว้างจอ(แถว[i]) for แถว in ทุกแถว) for i in range(4)]

    def ขีด(ซ้าย="+", กลาง="+", ขวา="+"):
        return ซ้าย + กลาง.join("-" * (ก + 2) for ก in กว้าง) + ขวา

    def บรรทัด(ค่า, ชิดขวาตั้งแต่=1):
        ช่อง = [" " + เติมให้เต็ม(ค่า[i], กว้าง[i], ชิดขวา=(i >= ชิดขวาตั้งแต่)) + " " for i in range(4)]
        return "|" + "|".join(ช่อง) + "|"

    print()
    print(ขีด())
    print(บรรทัด(หัวข้อ, ชิดขวาตั้งแต่=99))   # หัวตารางชิดซ้ายหมด
    print(ขีด())
    for แถว in แถวข้อความ:
        print(บรรทัด(แถว))
    print(ขีด())
    print(บรรทัด(แถวรวม))
    print(ขีด())
    if จำกัด and len(เรียงแล้ว) > จำกัด:
        print(f"  (แสดง {จำกัด} จาก {len(เรียงแล้ว)} PO — ที่เหลือดูในไฟล์ Excel "
              f"ส่วนบรรทัด 'รวมทั้งสิ้น' คิดครบทุก PO แล้ว)")
    print()


