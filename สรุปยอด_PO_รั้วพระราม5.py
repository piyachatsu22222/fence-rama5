    log.info("=" * 62)
    log.info(" สรุปยอด PO ตาม WBS — งานรั้ว โครงการ 4111")
    log.info("=" * 62)

    if not ค่า.source:
        log.error("โหมด wbs ต้องระบุไฟล์ต้นทางด้วย --source \"...\\4111_po.xlsx\"")
        return 1

    ที่มา = Path(ค่า.source)
    if not ที่มา.exists():
        log.error("ไม่พบไฟล์ต้นทาง: %s", ที่มา)
        return 2

    log.info("ไฟล์ต้นทาง : %s", ที่มา)
    log.info("ชีต        : %s (หัวตารางแถวที่ %d)", ค่า.sheet, ค่า.header_row)

    try:
        แถวทั้งหมด = อ่านแถว_SAP(ที่มา, ค่า.sheet, ค่า.header_row)
    except KeyError as ข้อผิดพลาด:
        log.error("%s", ข้อผิดพลาด.args[0])
