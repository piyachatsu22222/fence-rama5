def หาคอลัมน์(หัวตาราง: list[str], ชื่อที่ยอมรับ: list[str],
              คำบอกทิศทาง: tuple = ()) -> int | None:
    """
    หาว่าคอลัมน์ไหนคือคอลัมน์ที่ต้องการ ไล่ 3 รอบจากเข้มไปหลวม

      รอบ 1  ชื่อตรงเป๊ะกับลิสต์
      รอบ 2  มีชื่อในลิสต์อยู่ข้างใน (เฉพาะคำยาว ≥4 กันคำสั้นอย่าง po ไปโดน report)
      รอบ 3  เฉพาะคอลัมน์เงิน — หัวตารางต้องพูดถึงเงิน (ยอด/เงิน/จำนวน) + มีคำบอกทิศทาง (รับ/จ่าย)
             เผื่อไฟล์ตั้งชื่อแปลกกว่าที่ลิสต์ไว้ เช่น "จำนวนเงินที่จ่าย"

    รอบ 2 และ 3 จะข้ามหัวตารางที่ "ไม่ใช่ช่องเงิน" (วันที่จ่าย / กำหนดจ่าย / ผู้รับเหมา)
    ไม่งั้นคอลัมน์วันที่จะไปบังคอลัมน์ยอดเงิน แล้วยอดที่ได้จะผิด
    """
    เป็นคอลัมน์เงิน = bool(คำบอกทิศทาง)

    def ห้ามใช้(ข้อความ: str) -> bool:
        return เป็นคอลัมน์เงิน and any(คำ in ข้อความ for คำ in คำที่ไม่ใช่คอลัมน์เงิน)

    for ลำดับ, ข้อความ in enumerate(หัวตาราง):
        if ข้อความ and ข้อความ in ชื่อที่ยอมรับ:
            return ลำดับ
    for ลำดับ, ข้อความ in enumerate(หัวตาราง):
        if not ข้อความ or ห้ามใช้(ข้อความ):
            continue
        for ชื่อ in ชื่อที่ยอมรับ:
            if len(ชื่อ) >= 4 and ชื่อ in ข้อความ:
                return ลำดับ
    if เป็นคอลัมน์เงิน:
        for ลำดับ, ข้อความ in enumerate(หัวตาราง):
            if not ข้อความ or ห้ามใช้(ข้อความ):
                continue
            if (any(คำ in ข้อความ for คำ in คำที่แปลว่าเงิน)
                    and any(คำ in ข้อความ for คำ in คำบอกทิศทาง)):
                return ลำดับ
    return None


def หาหัวตาราง(แถวทั้งหมด: list[tuple], ลึกสุด: int = 30):
    """
    ไล่หาแถวหัวตารางใน 30 แถวแรก (เผื่อมีโลโก้/ชื่อโครงการอยู่ข้างบน)
    คืน (เลขแถวหัว, คอลัมน์PO, คอลัมน์ยอดรับ, คอลัมน์ยอดจ่าย) — ไม่เจอคืน None
    """
    for ลำดับ, แถว in enumerate(แถวทั้งหมด[:ลึกสุด]):
        หัว = [ปรับข้อความ(เซลล์) for เซลล์ in แถว]
        คอลัมน์po = หาคอลัมน์(หัว, ชื่อคอลัมน์_PO)
        คอลัมน์รับ = หาคอลัมน์(หัว, ชื่อคอลัมน์_ยอดรับ, คำบอกทิศทาง_รับ)
        คอลัมน์จ่าย = หาคอลัมน์(หัว, ชื่อคอลัมน์_ยอดจ่าย, คำบอกทิศทาง_จ่าย)
        if คอลัมน์รับ is not None and คอลัมน์รับ == คอลัมน์จ่าย:
            # หัวตารางเดียวกันโดนจับได้ทั้งสองฝั่ง (เช่น "ยอดรับ-จ่าย") — นับเป็นยอดรับอย่างเดียว กันยอดเบิ้ล
            คอลัมน์จ่าย = None
        if คอลัมน์po is not None and (คอลัมน์รับ is not None or คอลัมน์จ่าย is not None):
            return ลำดับ, คอลัมน์po, คอลัมน์รับ, คอลัมน์จ่าย
    return None


def เป็นแถวรวม(ข้อความ_po: str) -> bool:
    """เช็คว่าแถวนี้เป็นแถว 'รวมทั้งสิ้น' ของชีตเองหรือเปล่า (ถ้าใช่ต้องข้าม ไม่งั้นยอดเบิ้ล)"""
    เทียบ = ปรับข้อความ(ข้อความ_po)
    return any(คำ in เทียบ for คำ in คำที่แปลว่าแถวรวม)


def มีสูตรที่ยังไม่มีค่า(ที่อยู่: Path) -> bool:
    """
    เช็คว่าไฟล์นี้มีแต่สูตรที่ยังไม่เคยเซฟค่าไว้หรือเปล่า

    ต้องเปิดซ้ำด้วย data_only=False เพราะตอนอ่านปกติ (data_only=True) เซลล์สูตร
    ที่ไม่มีค่าแคชจะกลายเป็น None ไปแล้ว มองไม่เห็นว่าเคยเป็นสูตร
    """
    from openpyxl import load_workbook

    try:
        สมุดงาน = load_workbook(ที่อยู่, read_only=True, data_only=False)
    except Exception:
        return False
    try:
        for ชื่อชีต in สมุดงาน.sheetnames:
            for แถว in สมุดงาน[ชื่อชีต].iter_rows(values_only=True, max_row=500):
                for เซลล์ in แถว:
                    if isinstance(เซลล์, str) and เซลล์.startswith("="):
                        return True
    except Exception:
        return False
    finally:
        try:
            สมุดงาน.close()
        except Exception:
            pass
    return False


