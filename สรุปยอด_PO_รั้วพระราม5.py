def ปรับข้อความ(ค่า) -> str:
    """ตัดช่องว่าง/จุด/ขีด/วงเล็บ แล้วทำเป็นตัวพิมพ์เล็ก — ใช้เทียบชื่อคอลัมน์และคำค้น"""
    if ค่า is None:
        return ""
    return re.sub(r"[\s\.\-_/\\()\[\]:]+", "", str(ค่า)).strip().lower()


def ความกว้างจอ(ข้อความ: str) -> int:
    """นับความกว้างจริงบนหน้าจอ (สระ/วรรณยุกต์ไทยลอยบน ไม่กินที่)"""
    return sum(0 if ตัว in สระไทยไม่กินที่ else 1 for ตัว in str(ข้อความ))


def เติมให้เต็ม(ข้อความ: str, กว้าง: int, ชิดขวา: bool = False) -> str:
    """เติมช่องว่างให้ครบความกว้าง (คำนวณจากความกว้างจริงบนจอ)"""
    ข้อความ = str(ข้อความ)
    ขาด = max(0, กว้าง - ความกว้างจอ(ข้อความ))
    return (" " * ขาด + ข้อความ) if ชิดขวา else (ข้อความ + " " * ขาด)


def แปลงเป็นตัวเลข(ค่า):
    """
    แปลงค่าในเซลล์เป็น float
    รองรับ: 1,234.50 / (1,234.50) ที่แปลว่าติดลบ / มี ฿ หรือ 'บาท' / เลขไทย ๑๒๓ / ขีด '-' = 0
    คืน None ถ้าไม่ใช่ตัวเลข (เช่นข้อความหมายเหตุ)
    """
    if ค่า is None or isinstance(ค่า, bool):
        return None
    if isinstance(ค่า, (int, float)):
        return float(ค่า)
    ข้อความ = str(ค่า).strip()
    if not ข้อความ:
        return None
    ติดลบ = ข้อความ.startswith("(") and ข้อความ.endswith(")")
    ข้อความ = ข้อความ.strip("()").translate(เลขไทยเป็นอารบิก)
    ข้อความ = re.sub(r"[,\s\u00a0฿]|บาท|THB|thb", "", ข้อความ)
    if ข้อความ in {"-", "–", "—", ""}:
        return 0.0
    try:
        จำนวน = float(ข้อความ)
    except ValueError:
        return None
    return -จำนวน if ติดลบ else จำนวน


def จัดรูปแบบเงิน(จำนวน: float) -> str:
    """1234567.5 -> '1,234,567.50'"""
    return f"{จำนวน:,.2f}"


