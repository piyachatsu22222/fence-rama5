    log.info("\nอ่านข้อมูล %d แถว | ยอดรวมทุกหมวด %s บาท", len(แถวทั้งหมด), จัดรูปแบบเงิน(ยอดรวม))
    log.info("บันทึกผลสรุปที่ : %s", ที่อยู่ออก)
    return 0


