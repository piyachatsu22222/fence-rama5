def ตัวเลขหรือศูนย์(ค่า) -> float:
    """เหมือน แปลงเป็นตัวเลข() แต่ถ้าแปลงไม่ได้ให้เป็น 0 (ใช้กับคอลัมน์ปริมาณ/ราคา)"""
    return แปลงเป็นตัวเลข(ค่า) or 0.0


def ช่อง(แถว: tuple, ดัชนี: int):
    """ดึงค่าจากแถวแบบไม่พังถ้าแถวนั้นสั้นกว่าที่คาด"""
    return แถว[ดัชนี] if ดัชนี < len(แถว) else None


def อ่านแถว_SAP(ที่อยู่: Path, ชื่อชีต: str, แถวหัวตาราง: int) -> list[tuple]:
    """อ่านไฟล์ SAP ME2N export คืนเฉพาะแถวที่มีเลขที่เอกสาร (Purch.Doc.)"""
    import openpyxl
    สมุดงาน = openpyxl.load_workbook(ที่อยู่, data_only=True, read_only=True)
    try:
        if ชื่อชีต not in สมุดงาน.sheetnames:
            raise KeyError(
                f"ไม่พบชีตชื่อ '{ชื่อชีต}' ในไฟล์นี้ — ชีตที่มีคือ: "
                + ", ".join(สมุดงาน.sheetnames)
                + "\n  ระบุชีตที่ถูกต้องด้วย --sheet \"ชื่อชีต\""
            )
        ชีต = สมุดงาน[ชื่อชีต]
        return [
            แถว
            for แถว in ชีต.iter_rows(min_row=แถวหัวตาราง + 1, values_only=True)
            if ช่อง(แถว, คอลัมน์_เอกสาร) is not None
        ]
    finally:
        สมุดงาน.close()


def เรียงตามวันที่เอกสาร(แถว: tuple) -> str:
    """เรียงตามวันที่รูปแบบ dd.mm.yyyy — แปลงเป็น yyyymmdd ก่อนเทียบ"""
    ข้อความ = str(ช่อง(แถว, คอลัมน์_วันที่) or "")
    return ข้อความ[-4:] + ข้อความ[3:5] + ข้อความ[:2]


def มูลค่าของแถว(แถว: tuple) -> float:
    """มูลค่า = ปริมาณ x ราคาต่อหน่วย"""
    return ตัวเลขหรือศูนย์(ช่อง(แถว, คอลัมน์_ปริมาณ)) * ตัวเลขหรือศูนย์(ช่อง(แถว, คอลัมน์_ราคาต่อหน่วย))


