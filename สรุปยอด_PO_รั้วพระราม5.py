def main(argv=None) -> int:
    ค่า = อ่านอาร์กิวเมนต์(argv)
    เวลาเริ่ม = datetime.now()
    ตราเวลา = เวลาเริ่ม.strftime("%Y%m%d_%H%M")

    # ---- โหมด wbs: อ่าน SAP ME2N export ไฟล์เดียว ไม่ต้องค้นหาไฟล์ ----
    if ค่า.mode == "wbs":
        ที่อยู่ออก = Path(ค่า.out) if ค่า.out else Path.cwd() / f"สรุป_PO_WBS_{ตราเวลา}.txt"
        ตั้งค่า_log(ที่อยู่ออก.with_suffix(".log"))
        try:
            import openpyxl  # noqa: F401
        except ImportError:
            log.error("\nไม่พบไลบรารี openpyxl — ติดตั้งก่อนด้วยคำสั่ง:\n    pip install openpyxl\n")
            return 1
        return ทำงานโหมด_WBS(ค่า, ที่อยู่ออก)

    # ---- โหมด po (ค่าเริ่มต้น) ----
    ที่อยู่ออก = Path(ค่า.out) if ค่า.out else Path.cwd() / f"สรุปยอด_PO_{ตราเวลา}.xlsx"
    ตั้งค่า_log(None if ค่า.dry_run else ที่อยู่ออก.with_suffix(".log"))

    log.info("=" * 62)
    log.info(" สรุปยอด PO — งานรั้ว พระราม 5")
    log.info("=" * 62)
    log.info("คำค้น        : %s", ค่า.keyword)
    log.info("ช่วงวันที่แก้ไข : %s ถึง %s", ค่า.since, ค่า.until)

    # ---- ตรวจ openpyxl ก่อน จะได้ไม่ไปพังตอนอ่านไฟล์ ----
    try:
        import openpyxl  # noqa: F401
    except ImportError:
        log.error("\nไม่พบไลบรารี openpyxl — ติดตั้งก่อนด้วยคำสั่ง:\n    pip install openpyxl\n")
        return 1

    # ---- ตรวจรูปแบบวันที่ ----
    try:
        ตั้งแต่ = datetime.strptime(ค่า.since, "%Y-%m-%d")
        ถึง = datetime.strptime(ค่า.until, "%Y-%m-%d") + timedelta(days=1) - timedelta(seconds=1)
    except ValueError:
        log.error("รูปแบบวันที่ต้องเป็น YYYY-MM-DD เช่น 2023-06-01")
        return 1
    if ตั้งแต่ > ถึง:
        log.error("วันเริ่มต้นอยู่หลังวันสิ้นสุด — สลับค่า --since / --until ด้วย")
        return 1

    # ---- ขั้นที่ 1: ค้นหาไฟล์ ----
    es = None if ค่า.no_es else หา_es_exe(ค่า.es)
    ไฟล์ที่เจอ: list[Path] = []
    วิธีค้น = ""
    if es:
        log.info("เครื่องมือค้นหา : Everything (%s)", es)
        ไฟล์ที่เจอ = ค้นด้วย_Everything(es, ค่า.keyword, ค่า.since, ค่า.until)
        วิธีค้น = f"Everything ({es})"
    if not ไฟล์ที่เจอ:
        รากทั้งหมด = ค่า.root or [str(Path.home())]
        if not es:
            log.info("เครื่องมือค้นหา : สแกนเอง (ไม่พบ es.exe หรือสั่ง --no-es)")
        else:
            log.info("Everything ไม่คืนผล — สแกนโฟลเดอร์เองต่อ")
        ไฟล์ที่เจอ = สแกนโฟลเดอร์เอง(รากทั้งหมด, ค่า.keyword, ตั้งแต่, ถึง, ค่า.match_path)
        วิธีค้น = "สแกนเอง: " + ", ".join(รากทั้งหมด)

    # ตัดไฟล์ซ้ำ (Everything + สแกนเองอาจได้ตัวเดียวกัน) แล้วเรียงชื่อ
    # เก็บเป็นพาธเต็ม (resolve) เพื่อให้คอลัมน์ "พาธเต็ม" ในไฟล์สรุปไล่ย้อนกลับได้จริง
    # แม้จะสั่ง --root มาเป็นพาธสัมพัทธ์อย่าง ".\งานรั้ว"
    ไม่ซ้ำ = {}
    for ไฟล์ในรายการ in ไฟล์ที่เจอ:
        try:
            เต็ม = Path(ไฟล์ในรายการ).resolve()
        except OSError:
            เต็ม = Path(ไฟล์ในรายการ)
        ไม่ซ้ำ[str(เต็ม)] = เต็ม
    ไฟล์ที่เจอ = sorted(ไม่ซ้ำ.values(), key=lambda p: str(p).lower())
    log.info("พบไฟล์       : %d ไฟล์\n", len(ไฟล์ที่เจอ))

    if not ไฟล์ที่เจอ:
        log.warning("ไม่พบไฟล์ที่ตรงเงื่อนไข ลองทำอย่างใดอย่างหนึ่ง:")
        log.warning("  • ระบุโฟลเดอร์เอง เช่น --root \"D:\\งานรั้ว\"")
        log.warning("  • ลดคำค้นให้สั้นลง เช่น --keyword \"รั้ว\"")
        log.warning("  • ขยายช่วงวันที่ เช่น --since 2023-01-01 --until 2024-12-31")
        return 2

    for ที่อยู่ in ไฟล์ที่เจอ:
        log.info("  - %s", ที่อยู่)
    if ค่า.dry_run:
        log.info("\n(--dry-run: ยังไม่อ่านไฟล์ ถ้ารายชื่อถูกแล้วให้รันซ้ำโดยตัด --dry-run ออก)")
        return 0

    # ---- ขั้นที่ 2: อ่านทุกไฟล์ ----
    log.info("\nกำลังอ่านไฟล์...")
    รายการทั้งหมด: list[รายการเงิน] = []
    สถานะไฟล์: list[dict] = []
    อ่านสำเร็จ = 0
    for ที่อยู่ in ไฟล์ที่เจอ:
        try:
            รายการ, สถานะ = อ่านไฟล์เดียว(ที่อยู่)
        except Exception as ข้อผิดพลาด:      # กันพังทั้งงานเพราะไฟล์เดียว
            รายการ, สถานะ = [], f"ผิดพลาด: {type(ข้อผิดพลาด).__name__}: {ข้อผิดพลาด}"
            log.exception("อ่านไฟล์ไม่สำเร็จ: %s", ที่อยู่)
        รายการทั้งหมด.extend(รายการ)
        if รายการ:
            อ่านสำเร็จ += 1
        try:
            สถิติ = ที่อยู่.stat()
            แก้ไขเมื่อ = datetime.fromtimestamp(สถิติ.st_mtime).strftime("%Y-%m-%d %H:%M")
            ขนาด = round(สถิติ.st_size / 1024, 1)
        except OSError:
            แก้ไขเมื่อ, ขนาด = "-", 0
        สถานะไฟล์.append({"ชื่อ": ที่อยู่.name, "พาธ": str(ที่อยู่), "แก้ไข": แก้ไขเมื่อ,
                          "ขนาด": ขนาด, "สถานะ": สถานะ})
        log.info("  [%s] %s", "OK " if รายการ else "ข้าม", ที่อยู่.name)
        if not รายการ:
            log.info("        เหตุผล: %s", สถานะ)

    # ---- ขั้นที่ 3: รวมยอดตาม PO (แทน PivotTable) ----
    ตารางสรุป = รวมยอดตาม_PO(รายการทั้งหมด)
    รวมรับ = sum(ร.ยอดรับ for ร in ตารางสรุป.values())
    รวมจ่าย = sum(ร.ยอดจ่าย for ร in ตารางสรุป.values())

    log.info("\nสรุป: อ่านได้ %d/%d ไฟล์ | %d แถว | %d PO",
             อ่านสำเร็จ, len(ไฟล์ที่เจอ), len(รายการทั้งหมด), len(ตารางสรุป))
    พิมพ์ตารางสรุป(ตารางสรุป, ค่า.top)

    # ---- ขั้นที่ 4: เขียนไฟล์ Excel สรุป ----
    ข้อมูลการรัน = [
        ("รันเมื่อ", เวลาเริ่ม.strftime("%Y-%m-%d %H:%M:%S")),
        ("คำค้น", ค่า.keyword),
        ("ช่วงวันที่แก้ไขไฟล์", f"{ค่า.since} ถึง {ค่า.until}"),
        ("วิธีค้นหา", วิธีค้น),
        ("จำนวนไฟล์ที่พบ", len(ไฟล์ที่เจอ)),
        ("จำนวนไฟล์ที่อ่านได้", อ่านสำเร็จ),
        ("จำนวนแถวข้อมูล", len(รายการทั้งหมด)),
        ("จำนวน PO", len(ตารางสรุป)),
        ("ยอดรับรวม", จัดรูปแบบเงิน(รวมรับ)),
        ("ยอดจ่ายรวม", จัดรูปแบบเงิน(รวมจ่าย)),
        ("ยอดสุทธิรวม", จัดรูปแบบเงิน(รวมรับ - รวมจ่าย)),
    ]
    try:
        เขียนไฟล์สรุป(ที่อยู่ออก, ตารางสรุป, รายการทั้งหมด, สถานะไฟล์, ข้อมูลการรัน)
        log.info("เขียนไฟล์สรุปแล้ว : %s", ที่อยู่ออก)
        log.info("ไฟล์บันทึกการทำงาน : %s", ที่อยู่ออก.with_suffix(".log"))
    except PermissionError:
        log.error("เขียนไฟล์ไม่ได้ — ไฟล์ %s อาจเปิดค้างอยู่ใน Excel ปิดก่อนแล้วรันใหม่", ที่อยู่ออก)
        return 1
    except Exception as ข้อผิดพลาด:
        log.exception("เขียนไฟล์สรุปไม่สำเร็จ: %s", ข้อผิดพลาด)
        return 1
    return 0


if __name__ == "__main__":
    try:
        sys.exit(main())
    except KeyboardInterrupt:
        print("\nยกเลิกโดยผู้ใช้")
        sys.exit(130)
