def เช็คเท่ากับ(หัวข้อ: str, ได้, ควรได้) -> None:
    """เทียบค่าตัวเลข/ข้อความ พร้อมบอกว่าได้อะไรมาถ้าไม่ตรง"""
    if isinstance(ได้, float) or isinstance(ควรได้, float):
        ตรง = ได้ is not None and abs(float(ได้) - float(ควรได้)) < 0.005
    else:
        ตรง = ได้ == ควรได้
    เช็ค(หัวข้อ, ตรง, "" if ตรง else f"ได้ {ได้!r} ควรได้ {ควรได้!r}")


