def สรุปผล() -> int:
    ผ่าน = sum(1 for _, ok, _ in ผลทดสอบ if ok)
    ตก = [(หัวข้อ, รายละเอียด) for หัวข้อ, ok, รายละเอียด in ผลทดสอบ if not ok]
    print("\n" + "=" * 62)
    print(f" ผลทดสอบ: ผ่าน {ผ่าน}/{len(ผลทดสอบ)} ข้อ")
    print("=" * 62)
    for หัวข้อ, รายละเอียด in ตก:
        print(f"  [ไม่ผ่าน] {หัวข้อ}" + (f"  ({รายละเอียด})" if รายละเอียด else ""))
    if not ตก:
        print("  ผ่านหมดทุกข้อ — สคริปต์สรุปยอดยังคำนวณถูกอยู่")
    print()
    return 0 if not ตก else 1


