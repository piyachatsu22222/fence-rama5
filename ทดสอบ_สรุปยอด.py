def ทดสอบทั้งกระบวนการ(ตัวหลัก, ฐาน: Path) -> None:
    """รันจริงตั้งแต่ค้นไฟล์ยันเขียนไฟล์สรุป แล้วเทียบยอดกับที่คำนวณด้วยมือ"""
    ไฟล์สรุป = ฐาน / "ผลลัพธ์ทดสอบ.xlsx"
    # สั่ง --root เป็นพาธสัมพัทธ์ ("." ) โดยตั้งใจ เพื่อเช็คว่าไฟล์สรุปยังบันทึกพาธเต็มให้ถูก
    เดิม = Path.cwd()
    os.chdir(ฐาน)
    try:
        รหัสจบ = ตัวหลัก.main([
            "--no-es", "--root", ".", "--out", str(ไฟล์สรุป),
            "--since", "2023-06-01", "--until", "2024-02-29",
        ])
    finally:
        os.chdir(เดิม)
    เช็คเท่ากับ("รันจบด้วยรหัส 0", รหัสจบ, 0)
    เช็ค("เขียนไฟล์สรุปออกมาจริง", ไฟล์สรุป.exists())
    if not ไฟล์สรุป.exists():
        return

    from openpyxl import load_workbook
    สมุด = load_workbook(ไฟล์สรุป)
    เช็คเท่ากับ("ไฟล์สรุปมี 4 ชีต", สมุด.sheetnames,
                ["สรุปตาม PO", "รายละเอียด", "ไฟล์ที่อ่าน", "ข้อมูลการรัน"])

    ชีตสรุป = สมุด["สรุปตาม PO"]
    แถวข้อมูล = [แถว for แถว in ชีตสรุป.iter_rows(min_row=2, values_only=True) if แถว[0]]
    แถวรวมท้าย = แถวข้อมูล[-1] if แถวข้อมูล else ()
    ตาราง = {แถว[0]: แถว for แถว in แถวข้อมูล[:-1]}   # ตัดแถว "รวมทั้งสิ้น" ท้ายตารางออก

    # ยอดที่คำนวณด้วยมือจากไฟล์ทดสอบ
    ควรได้ = {
        # PO           ยอดรับ        ยอดจ่าย                      ยอดสุทธิ
        "PO-6606-001": (400000.0, 220000.0, 180000.0),      # 250000+150000+0 / 120000+105000-5000
        "PO-6607-002": (2080000.5, 1150000.0, 930000.5),    # 80000+2000000.50 / 0+1150000
        "PO-6702-003": (90000.0, 45000.25, 44999.75),
        "PO-6612-004": (500000.0, 300000.0, 200000.0),      # ต้องไม่เอาคอลัมน์วันที่มาบวก
    }
    เช็คเท่ากับ("จำนวน PO ที่สรุปได้", len(ตาราง), len(ควรได้))
    for po, (รับ, จ่าย, สุทธิ) in ควรได้.items():
        if po not in ตาราง:
            เช็ค(f"{po} ต้องอยู่ในสรุป", False, f"มีแต่ {sorted(ตาราง)}")
            continue
        เช็คเท่ากับ(f"{po} ยอดรับ", ตาราง[po][1], รับ)
        เช็คเท่ากับ(f"{po} ยอดจ่าย", ตาราง[po][2], จ่าย)
        เช็คเท่ากับ(f"{po} ยอดสุทธิ", ตาราง[po][3], สุทธิ)

    เช็ค("ไม่หยิบไฟล์ที่คำค้นไม่ครบ (ราชพฤกษ์)", "PO-ไม่เกี่ยว".upper() not in ตาราง)
    เช็ค("ไม่หยิบไฟล์ที่วันที่นอกช่วง", "PO-นอกช่วง".upper() not in ตาราง)
    เช็ค("ไม่เอาแถวรวมของไฟล์ต้นทางมานับเป็น PO",
         not any(ตัวหลัก.เป็นแถวรวม(po) for po in ตาราง), f"ได้ {sorted(ตาราง)}")

    # แถวรวมท้ายตารางต้องเป็นสูตร SUM จริง ไม่ใช่ตัวเลขนิ่ง ๆ
    เช็คเท่ากับ("แถวสุดท้ายคือ 'รวมทั้งสิ้น'", แถวรวมท้าย[0] if แถวรวมท้าย else None, "รวมทั้งสิ้น")
    เช็ค("ยอดรวมเป็นสูตร SUM",
         bool(แถวรวมท้าย) and str(แถวรวมท้าย[1]).startswith("=SUM("),
         f"ได้ {แถวรวมท้าย[1]!r}" if แถวรวมท้าย else "ไม่มีแถวรวม")

    # ไฟล์ที่มีแต่สูตรต้องบอกเหตุผลให้ถูก จะได้รู้ว่าต้องไปกดเซฟใน Excel
    สถานะ = {แถว[0]: แถว[3] for แถว in สมุด["ไฟล์ที่อ่าน"].iter_rows(min_row=2, values_only=True) if แถว[0]}
    ไฟล์สูตร = "รั้ว พระราม 5 สูตรล้วน.xlsx"
    เช็ค("บอกเหตุผลไฟล์ที่มีแต่สูตรถูกต้อง",
         ไฟล์สูตร in สถานะ and "สูตร" in str(สถานะ[ไฟล์สูตร]),
         f"ได้ {สถานะ.get(ไฟล์สูตร)!r}")

    # คอลัมน์พาธเต็มต้องเป็นพาธเต็มจริง ไว้ไล่ย้อนกลับได้
    พาธ = [แถว[6] for แถว in สมุด["รายละเอียด"].iter_rows(min_row=2, values_only=True) if แถว[0]]
    เช็ค("คอลัมน์พาธเต็มเป็นพาธเต็มจริง",
         bool(พาธ) and all(Path(p).is_absolute() for p in พาธ),
         f"ได้ {พาธ[:1]}")
    สมุด.close()


